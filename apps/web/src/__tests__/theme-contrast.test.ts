// WCAG 2.1 colour-contrast guarantee for the theme tokens (UX-S-010). The e2e
// a11y sweep runs axe's `color-contrast` on the *default* theme only; this unit
// test extends that guarantee to every theme's token definitions — no browser
// needed — so a token edit that regresses contrast fails CI here.
//
// Scope of the promise (grounded in an audit of all 60 themes):
//  - `text-primary` is the main readable text and MUST meet AA (4.5:1) on both
//    core surfaces in EVERY theme.
//  - Studio's own designed themes (the 5 built-ins + the 4 "high-contrast"
//    variants, whose contrast is an explicit promise) must meet AA on
//    primary / muted / dim.
//  - No theme may drop any of those pairs below the 3:1 large-text floor, save a
//    single pinned exception: community palettes' `text-dim` faithfully
//    replicates the source editor's comment colour (e.g. Dracula, Tokyo Night),
//    which the real palettes render at sub-AA too — matching them is the point.
//    Only `tokyo-night-day` dips below 3:1; it is allow-listed and pinned so any
//    NEW severe drop fails.
//  - Tone-coloured text (`text-<tone>-fg`: status chips, primary buttons, the
//    active tab) MUST meet AA in EVERY theme, on the bare surfaces and on the
//    10% / 15% tints of its own tone the primitives paint behind it. Those
//    tokens are generated (scripts/gen-status-fg.mjs), so this also fails when
//    a theme was edited or added without regenerating them.
//  - A diff's added and removed lines MUST show in EVERY theme. The tint this
//    replaced, 10% of the tone, landed one just-noticeable step from the page on
//    Solarized Dark, and nothing failed, because nothing looked. So the second
//    half of this file takes what a marked row is made of (its generated tint,
//    its edge, its line number) and measures, on each theme's page, what a
//    reader has to tell apart: the tint from the page, the code and the line
//    number on the tint, and the two edges from the page and from each other.
//    `primitives/diffRow.test.ts` in ui-components holds the row's classes to
//    the same parts.
//  - The label of a solid accent button (`text-on-accent`) MUST meet AA in EVERY
//    theme on its fill (`bg-accent`) and on its hover (`bg-accent-hover`), and
//    the hover must be a step anyone can see. Both are generated by the same
//    script; the third part of this file measures them.

const css = readFileSync(resolve(__dirname, '../styles/global.css'), 'utf8');

const BUILTIN = new Set([
  'studio-dark',
  'graphite-dark',
  'midnight-blue',
  'workbench-light',
  'paper-light',
]);
const HIGH_CONTRAST = new Set([
  'high-contrast-dark',
  'high-contrast-light',
  'github-dark-high-contrast',
  'github-light-high-contrast',
]);

type RGB = [number, number, number];
const linear = (c: number): number => {
  const s = c / 255;
  return s <= 0.03928 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
};
const luminance = (rgb: RGB): number =>
  0.2126 * linear(rgb[0]) + 0.7152 * linear(rgb[1]) + 0.0722 * linear(rgb[2]);
const contrast = (a: RGB, b: RGB): number => {
  const hi = Math.max(luminance(a), luminance(b));
  const lo = Math.min(luminance(a), luminance(b));
  return (hi + 0.05) / (lo + 0.05);
};

interface Theme {
  id: string;
  tokens: Record<string, RGB>;
}
const themes: Theme[] = [];
for (const block of css.matchAll(/\[data-theme='([^']+)'\]\s*\{([^}]*)\}/g)) {
  const tokens: Record<string, RGB> = {};
  for (const tok of block[2].matchAll(/--([\w-]+):\s*(\d+)\s+(\d+)\s+(\d+)\s*;/g)) {
    tokens[tok[1]] = [Number(tok[2]), Number(tok[3]), Number(tok[4])];
  }
  themes.push({ id: block[1], tokens });
}

const AA = 4.5;
const LARGE = 3;
const SURFACES = ['surface', 'card'] as const;

const failing = (fgs: string[], threshold: number, filter: (id: string) => boolean): string[] => {
  const out: string[] = [];
  for (const { id, tokens } of themes) {
    if (!filter(id)) continue;
    for (const fg of fgs) {
      for (const bg of SURFACES) {
        if (!tokens[fg] || !tokens[bg]) continue;
        if (contrast(tokens[fg], tokens[bg]) < threshold) out.push(`${id} ${fg}/${bg}`);
      }
    }
  }
  return out;
};

describe('theme colour contrast (WCAG 2.1 AA)', () => {
  it('parses a token block for every catalogued theme', () => {
    expect(themes.length).toBeGreaterThanOrEqual(60);
    for (const { tokens } of themes) expect(tokens['text-primary']).toBeDefined();
  });

  it('primary text meets AA (4.5:1) on surface and card in EVERY theme', () => {
    expect(failing(['text-primary'], AA, () => true)).toEqual([]);
  });

  it("Studio's built-in + high-contrast themes meet AA on primary / muted / dim", () => {
    const designed = (id: string) => BUILTIN.has(id) || HIGH_CONTRAST.has(id);
    expect(failing(['text-primary', 'text-muted', 'text-dim'], AA, designed)).toEqual([]);
  });

  it('no theme drops primary / muted / dim below the 3:1 large-text floor (one pinned community exception)', () => {
    expect(failing(['text-primary', 'text-muted', 'text-dim'], LARGE, () => true)).toEqual([
      'tokyo-night-day text-dim/card',
    ]);
  });

  it('every theme sets its own status tones — none are inherited from the default theme', () => {
    const missing: string[] = [];
    for (const { id, tokens } of themes) {
      for (const tone of FG_TONES) {
        if (!tokens[tone]) missing.push(`${id} --${tone}`);
        if (!tokens[`${tone}-fg`]) missing.push(`${id} --${tone}-fg`);
      }
    }
    expect(missing).toEqual([]);
  });

  it('tone-coloured text meets AA on both surfaces and on its own 10% / 15% tint in EVERY theme', () => {
    const out: string[] = [];
    for (const { id, tokens } of themes) {
      for (const tone of FG_TONES) {
        const fg = tokens[`${tone}-fg`];
        for (const bg of SURFACES) {
          for (const alpha of FG_TINTS) {
            const backdrop = composite(tokens[tone], tokens[bg], alpha) as RGB;
            if (contrast(fg, backdrop) < FG_MIN_CONTRAST) {
              out.push(`${id} ${tone}-fg on ${tone}/${alpha * 100} over ${bg}`);
            }
          }
        }
      }
    }
    expect(out).toEqual([]);
  });

  it('the generated tokens are current (run `node scripts/gen-status-fg.mjs` after editing a theme)', () => {
    expect(generate(css)).toBe(css);
  });
});

/**
 * What a marked line of a diff is made of, as the generator solves it: the token
 * of its tint, the tone of its edge, and the colour of its line number.
 * `primitives/diffRow.test.ts` holds the row's classes to exactly these, so what
 * is measured here is what is drawn.
 */
interface DiffRowParts {
  tint: string;
  edge: string;
  number: string;
}
const MARKED = ['add', 'del'] as const;
const DIFF_ROWS: Record<(typeof MARKED)[number], DiffRowParts> = {
  add: { tint: 'diff-add', edge: DIFF_TINTS.add, number: DIFF_NUMBER },
  del: { tint: 'diff-del', edge: DIFF_TINTS.del, number: DIFF_NUMBER },
};

/** The edge is the tone itself: it must be plainly not the page, and plainly not the other edge. */
const EDGE_FROM_PAGE = 25;
const EDGE_FROM_EDGE = 15;

const toRgb = (colour: readonly number[]): RGB => [colour[0], colour[1], colour[2]];

/** Everything a theme's diff rows fall short on, as lines that name the row and the measure. */
function shortfalls(theme: Theme, rows = DIFF_ROWS): string[] {
  const { tokens } = theme;
  const page = tokens[DIFF_PAGE];
  const out: string[] = [];
  const check = (what: string, value: number, least: number): void => {
    if (value < least) out.push(`${theme.id}: ${what} is ${value.toFixed(1)}, under ${least}`);
  };
  for (const kind of MARKED) {
    const { tint, edge, number } = rows[kind];
    const row = tokens[tint];
    check(`the ${kind} tint against the page`, difference(row, page), DIFF_TINT_TARGET);
    check(`the code on the ${kind} tint`, contrast(tokens[DIFF_CODE], row), DIFF_CODE_MIN_CONTRAST);
    check(
      `the line number on the ${kind} tint`,
      contrast(tokens[number], row),
      DIFF_NUMBER_MIN_CONTRAST,
    );
    check(`the ${kind} edge against the page`, difference(tokens[edge], page), EDGE_FROM_PAGE);
  }
  check(
    'the add edge against the del edge',
    difference(tokens[rows.add.edge], tokens[rows.del.edge]),
    EDGE_FROM_EDGE,
  );
  return out;
}

/** `theme` with its diff tints replaced by the tone at one fixed share over the page. */
function withFixedTint(theme: Theme, alpha: number): Theme {
  const tokens = { ...theme.tokens };
  for (const kind of MARKED) {
    tokens[`diff-${kind}`] = toRgb(
      composite(tokens[DIFF_TINTS[kind]], tokens[DIFF_PAGE], alpha).map(Math.round),
    );
  }
  return { id: theme.id, tokens };
}

describe('a diff row shows on every theme', () => {
  const themeOf = (id: string): Theme => {
    const theme = themes.find((t) => t.id === id);
    if (!theme) throw new Error(`no theme '${id}'`);
    return theme;
  };

  it('every theme defines what a row is made of (a guard that read nothing would pass anything)', () => {
    const asked = [
      DIFF_PAGE,
      DIFF_CODE,
      ...MARKED.flatMap((kind) => Object.values(DIFF_ROWS[kind])),
    ];
    expect([...new Set(asked)].sort()).toEqual([
      'danger',
      'diff-add',
      'diff-del',
      'success',
      'surface',
      'text-muted',
      'text-primary',
    ]);
    for (const { id, tokens } of themes) {
      expect(Object.keys(tokens), id).toEqual(expect.arrayContaining(asked));
    }
    expect(() => themeOf('no-such-theme')).toThrow("no theme 'no-such-theme'");
  });

  it('an added and a removed line stand out, can be read, and can be told apart', () => {
    expect(themes.flatMap((theme) => shortfalls(theme))).toEqual([]);
  });

  it('fails on the tint this replaced: 10% of the tone was lost on Solarized Dark', () => {
    // The removed line at the edge of what an eye can tell from the page at all.
    expect(shortfalls(withFixedTint(themeOf('solarized-dark'), 0.1))).toEqual([
      expect.stringMatching(/^solarized-dark: the add tint against the page is 4\.\d, under 10$/),
      expect.stringMatching(
        /^solarized-dark: the del tint against the page is [12]\.\d, under 10$/,
      ),
    ]);
  });

  it('no one share of the tone does for every theme, which is why each has its own', () => {
    // 20% keeps every line readable and leaves some too faint to see...
    const floor = themes.flatMap((theme) =>
      shortfalls(withFixedTint(theme, DIFF_TINT_FLOOR / 100)),
    );
    expect(floor.length).toBeGreaterThan(0);
    expect(floor.every((line) => line.includes('tint against the page'))).toBe(true);
    expect(floor).toContainEqual(
      expect.stringMatching(/^solarized-dark: the del tint against the page is 5\.\d, under 10$/),
    );
    // ...and the share that lifts those takes the code under AA somewhere else.
    const lifted = themes.flatMap((theme) => shortfalls(withFixedTint(theme, 0.33)));
    expect(lifted.some((line) => line.includes('the code on the'))).toBe(true);
  });

  it('keeps the floor where it stands off the page, and raises it only where it does not', () => {
    let kept = 0;
    let raised = 0;
    for (const { id, tokens } of themes) {
      const page = tokens[DIFF_PAGE];
      for (const kind of MARKED) {
        const tint = tokens[`diff-${kind}`];
        const floor = composite(tokens[DIFF_TINTS[kind]], page, DIFF_TINT_FLOOR / 100).map(
          Math.round,
        );
        if (difference(floor, page) >= DIFF_TINT_TARGET) {
          expect(tint, `${id} ${kind}`).toEqual(floor);
          kept += 1;
        } else {
          expect(difference(tint, page), `${id} ${kind}`).toBeGreaterThan(difference(floor, page));
          raised += 1;
        }
      }
    }
    expect(kept).toBeGreaterThan(0);
    expect(raised).toBeGreaterThan(0);
  });

  it('fails on a tint too strong to read code on, on edges of one colour, and on a number too dim', () => {
    const heavy = themes.flatMap((theme) => shortfalls(withFixedTint(theme, 0.6)));
    expect(heavy.some((line) => line.includes('the code on the del tint'))).toBe(true);

    const theme = themes[0];
    const oneEdge = { ...DIFF_ROWS, add: { ...DIFF_ROWS.add, edge: DIFF_ROWS.del.edge } };
    expect(shortfalls(theme, oneEdge)).toEqual([
      `${theme.id}: the add edge against the del edge is 0.0, under ${EDGE_FROM_EDGE}`,
    ]);
    const faintEdge = { ...DIFF_ROWS, del: { ...DIFF_ROWS.del, edge: 'card' } };
    expect(shortfalls(theme, faintEdge)).toContainEqual(
      expect.stringContaining('the del edge against the page'),
    );
    const dimNumber = { ...DIFF_ROWS, add: { ...DIFF_ROWS.add, number: 'surface' } };
    expect(shortfalls(theme, dimNumber)).toContainEqual(
      expect.stringContaining('the line number on the add tint'),
    );
  });
});

describe('a solid accent button reads on every theme', () => {
  const BLACK: RGB = [0, 0, 0];
  const WHITE: RGB = [255, 255, 255];

  it('every theme defines the label and the hover of a solid accent button', () => {
    const missing = themes.flatMap(({ id, tokens }) =>
      ['accent', 'on-accent', 'accent-hover']
        .filter((name) => !tokens[name])
        .map((n) => `${id} --${n}`),
    );
    expect(missing).toEqual([]);
  });

  it('the label meets AA on the fill and on the hover in EVERY theme', () => {
    const out: string[] = [];
    for (const { id, tokens } of themes) {
      for (const fill of ['accent', 'accent-hover']) {
        const ratio = contrast(tokens['on-accent'], tokens[fill]);
        if (ratio < ON_ACCENT_MIN_CONTRAST)
          out.push(`${id} on-accent on ${fill}: ${ratio.toFixed(2)}`);
      }
    }
    expect(out).toEqual([]);
  });

  it('the hover is a step anyone can see, and only ever moves away from the label', () => {
    const out: string[] = [];
    for (const { id, tokens } of themes) {
      const step = difference(tokens['accent-hover'], tokens.accent);
      if (step < ACCENT_HOVER_TARGET) out.push(`${id}: hover is ${step.toFixed(1)} from the fill`);
      const label = tokens['on-accent'];
      if (contrast(label, tokens['accent-hover']) < contrast(label, tokens.accent)) {
        out.push(`${id}: the label reads worse on the hover`);
      }
    }
    expect(out).toEqual([]);
  });

  it("uses the theme's own colour wherever one reads, and black or white only where none does", () => {
    let own = 0;
    let fallback = 0;
    for (const { id, tokens } of themes) {
      const poles = [tokens.surface, tokens['text-primary']];
      const best = Math.max(...poles.map((pole) => contrast(pole, tokens.accent)));
      if (best >= ON_ACCENT_MIN_CONTRAST) {
        expect(poles, id).toContainEqual(tokens['on-accent']);
        own += 1;
      } else {
        expect([BLACK, WHITE], id).toContainEqual(tokens['on-accent']);
        fallback += 1;
      }
    }
    expect(own).toBeGreaterThan(0);
    expect(fallback).toBeGreaterThan(0);
  });

  it('no one label colour does for every theme, which is why each has its own', () => {
    const under = (label: RGB): string[] =>
      themes
        .filter(({ tokens }) => contrast(label, tokens.accent) < ON_ACCENT_MIN_CONTRAST)
        .map(({ id }) => id);
    expect(under(WHITE)).toContain('solarized-light');
    expect(under(BLACK)).toContain('github-light');
  });

  describe('solveOnAccent', () => {
    const yellow: RGB = [255, 215, 0];

    it('takes whichever of the two theme colours stands out more on the accent', () => {
      expect(solveOnAccent(yellow, BLACK, WHITE)).toEqual(BLACK);
      expect(solveOnAccent(yellow, WHITE, BLACK)).toEqual(BLACK);
    });

    it('falls back to white where neither theme colour reads and white reads better', () => {
      const blue: RGB = [9, 105, 218];
      expect(contrast([215, 215, 215], blue)).toBeLessThan(ON_ACCENT_MIN_CONTRAST);
      expect(contrast([40, 40, 40], blue)).toBeLessThan(ON_ACCENT_MIN_CONTRAST);
      expect(solveOnAccent(blue, [215, 215, 215], [40, 40, 40])).toEqual(WHITE);
    });

    it('falls back to black where neither theme colour reads and black reads better', () => {
      const blue: RGB = [38, 139, 210];
      expect(solveOnAccent(blue, [253, 246, 227], [60, 60, 60])).toEqual(BLACK);
      expect(contrast(BLACK, blue)).toBeGreaterThan(contrast(WHITE, blue));
    });
  });

  describe('solveAccentHover', () => {
    const grey: RGB = [128, 128, 128];
    const at = (toward: RGB, accent: RGB, share: number): RGB =>
      toRgb(composite(toward, accent, share / 100).map(Math.round));

    it('darkens under a light label and lightens under a dark one, by the least that shows', () => {
      // 10% is 4.4 from the grey; 14% the first share at the target.
      expect(difference(at(BLACK, grey, ACCENT_HOVER_FLOOR), grey)).toBeLessThan(
        ACCENT_HOVER_TARGET,
      );
      expect(solveAccentHover(grey, WHITE)).toEqual(at(BLACK, grey, 14));
      expect(solveAccentHover(grey, BLACK)).toEqual(at(WHITE, grey, 14));
      expect(difference(at(BLACK, grey, 13), grey)).toBeLessThan(ACCENT_HOVER_TARGET);
    });

    it('stops at the ceiling where no share shows: near black, darker is no different', () => {
      const ink: RGB = [10, 10, 10];
      const hover = solveAccentHover(ink, WHITE);
      expect(hover).toEqual(at(BLACK, ink, ACCENT_HOVER_CEILING));
      expect(difference(hover, ink)).toBeLessThan(ACCENT_HOVER_TARGET);
    });
  });
});

/**
 * What the standalone header's Lens link (`LensLink` in ui-components'
 * layout/TopBar.tsx) is drawn with: each part a token and the share of it
 * painted over the bar (`bg-card`). At rest a label on its own fill inside an
 * edge; on hover a label over a tint of the accent inside an accent edge; and a
 * focus ring. `TopBar.test.tsx` holds the link's classes to exactly these, so
 * what is measured here is what is drawn. `fill: null` is no fill: the bar
 * shows through.
 */
interface LinkPart {
  token: string;
  share: number;
}
interface LinkParts {
  label: LinkPart;
  fill: LinkPart | null;
  edge: LinkPart;
  hoverLabel: LinkPart;
  hoverFill: LinkPart;
  hoverEdge: LinkPart;
  ring: LinkPart;
}
const whole = (token: string): LinkPart => ({ token, share: 1 });
const LENS_LINK: LinkParts = {
  label: whole('text-primary'),
  fill: whole('surface'),
  edge: whole('border'),
  hoverLabel: whole('accent-fg'),
  hoverFill: { token: 'accent', share: 0.1 },
  hoverEdge: { token: 'accent', share: 0.4 },
  ring: whole('accent-fg'),
};
/** The first look of the link, before these measures: the same shape in other tokens. */
const LENS_LINK_FIRST_DRAFT: LinkParts = {
  label: whole('text-muted'),
  fill: null,
  edge: whole('border-subtle'),
  hoverLabel: whole('accent'),
  hoverFill: { token: 'accent', share: 0.1 },
  hoverEdge: { token: 'accent', share: 0.4 },
  ring: { token: 'accent', share: 0.7 },
};
const LINK_BAR = 'card';
/** OKLab x100. About 2 is the least an eye can tell apart; a button's outline wants a clear step more. */
const LINK_OUTLINE_FROM_BAR = 3;
/** OKLab x100. The hover edge must be plainly not the resting edge. */
const LINK_HOVER_EDGE_STEP = 5;
/** WCAG 2.2 non-text contrast (1.4.11) for the focus ring against the bar. */
const LINK_RING_MIN_CONTRAST = 3;

/** Everything the link falls short on in `theme`, as lines that name the part and the measure. */
function linkShortfalls(theme: Theme, parts: LinkParts): string[] {
  const { tokens } = theme;
  const bar = tokens[LINK_BAR];
  const paint = ({ token, share }: LinkPart): RGB => toRgb(composite(tokens[token], bar, share));
  const fill = parts.fill ? paint(parts.fill) : bar;
  const out: string[] = [];
  const check = (what: string, value: number, least: number): void => {
    if (value < least) out.push(`${theme.id}: ${what} is ${value.toFixed(1)}, under ${least}`);
  };
  check('the label on its fill', contrast(paint(parts.label), fill), AA);
  check(
    'the outline against the bar',
    Math.max(difference(paint(parts.edge), bar), difference(fill, bar)),
    LINK_OUTLINE_FROM_BAR,
  );
  check(
    'the hover label on its tint',
    contrast(paint(parts.hoverLabel), paint(parts.hoverFill)),
    AA,
  );
  check(
    'the hover edge against the resting edge',
    difference(paint(parts.hoverEdge), paint(parts.edge)),
    LINK_HOVER_EDGE_STEP,
  );
  check('the focus ring against the bar', contrast(paint(parts.ring), bar), LINK_RING_MIN_CONTRAST);
  return out;
}

describe("the header's Lens link reads on every theme", () => {
  it('every theme defines what the link is made of (a guard that read nothing would pass anything)', () => {
    const asked = [
      LINK_BAR,
      ...Object.values(LENS_LINK).flatMap((part: LinkPart | null) => (part ? [part.token] : [])),
    ];
    expect([...new Set(asked)].sort()).toEqual([
      'accent',
      'accent-fg',
      'border',
      'card',
      'surface',
      'text-primary',
    ]);
    for (const { id, tokens } of themes) {
      expect(Object.keys(tokens), id).toEqual(expect.arrayContaining(asked));
    }
  });

  it('its label, outline, hover and focus ring all hold in EVERY theme', () => {
    expect(themes.flatMap((theme) => linkShortfalls(theme, LENS_LINK))).toEqual([]);
  });

  it('fails on its first draft: faint on Tokyo Night Day, no edge on Rose Pine, an unreadable hover on Ayu Light', () => {
    const shortfalls = themes.flatMap((theme) => linkShortfalls(theme, LENS_LINK_FIRST_DRAFT));
    expect(shortfalls).toEqual(
      expect.arrayContaining([
        'tokyo-night-day: the label on its fill is 3.9, under 4.5',
        'rose-pine: the outline against the bar is 0.0, under 3',
        'ayu-light: the hover label on its tint is 2.0, under 4.5',
        'ayu-light: the focus ring against the bar is 1.7, under 3',
      ]),
    );
    // The bare accent as hover text is the widest miss: nearly half the themes.
    const hover = shortfalls.filter((line) => line.includes('the hover label'));
    expect(hover.length).toBeGreaterThanOrEqual(25);
  });
});

/**
 * A tone-coloured part of the header's controls (the top bar's panel buttons,
 * the tab strip's tabs and mode buttons, and the workspace status chip), the
 * backdrop it is drawn on, and the least it needs: 4.5:1 for a label, 3:1 for
 * an icon or a focus ring. The bar under all of them is `bg-card`. `on` is what
 * lies between the part and the bar, painted bottom first; none is the bar.
 */
interface HeaderPart {
  what: string;
  fg: LinkPart;
  on: LinkPart[];
  least: number;
}
/** WCAG 2.1 1.4.11: an icon, or a focus ring, against what is next to it. */
const NON_TEXT_MIN_CONTRAST = 3;
const tint = (token: string, share: number): LinkPart => ({ token, share });

/**
 * The header's tone-coloured parts, with `tone` the colour each tone is drawn
 * in, `ring` the focus ring's, and `workspaceCount` the fill of the unpushed
 * count while the status chip, on the Workspace page, is itself an accent tint.
 * The classes in TopBar.tsx, PanelTabs.tsx and WorkspaceStatusChip.tsx are
 * these; their tests hold them to it.
 */
function headerParts(
  tone: (name: 'accent' | 'warning') => LinkPart,
  ring: LinkPart,
  workspaceCount: LinkPart,
): HeaderPart[] {
  const accent = tone('accent');
  return [
    { what: 'the focus ring against the bar', fg: ring, on: [], least: NON_TEXT_MIN_CONTRAST },
    { what: "the active tab's label", fg: accent, on: [tint('accent', 0.15)], least: AA },
    {
      what: "a mode button's icon",
      fg: accent,
      on: [whole('surface')],
      least: NON_TEXT_MIN_CONTRAST,
    },
    {
      what: "the current mode's icon",
      fg: accent,
      on: [tint('accent', 0.15)],
      least: NON_TEXT_MIN_CONTRAST,
    },
    {
      what: "a mode button's chevron on hover",
      fg: accent,
      on: [tint('accent', 0.1)],
      least: NON_TEXT_MIN_CONTRAST,
    },
    {
      what: "the open panel's top-bar icon",
      fg: accent,
      on: [tint('accent', 0.1)],
      least: NON_TEXT_MIN_CONTRAST,
    },
    {
      what: "the status chip's label on the Workspace page",
      fg: accent,
      on: [tint('accent', 0.1)],
      least: AA,
    },
    {
      what: "the locked status chip's label",
      fg: tone('warning'),
      on: [tint('warning', 0.1)],
      least: AA,
    },
    {
      what: 'the unpushed count',
      fg: accent,
      on: [whole('surface'), tint('accent', 0.15)],
      least: AA,
    },
    {
      what: 'the unpushed count on the Workspace page',
      fg: accent,
      on: [tint('accent', 0.1), workspaceCount],
      least: AA,
    },
    {
      what: "the repository's name on the Workspace page",
      fg: whole('text-primary'),
      on: [tint('accent', 0.1)],
      least: AA,
    },
    {
      what: "the repository's name on a locked chip",
      fg: whole('text-primary'),
      on: [tint('warning', 0.1)],
      least: AA,
    },
  ];
}
const HEADER_PARTS = headerParts((name) => whole(`${name}-fg`), whole('accent-fg'), whole('card'));
/**
 * What the header drew before: the bare tones, a ring at 70% of the accent, and
 * the count's tint over the chip's.
 */
const HEADER_PARTS_BEFORE = headerParts(
  (name) => whole(name),
  tint('accent', 0.7),
  tint('accent', 0.15),
);
/** The readable colours with the count's tint kept over the chip's: too much accent for `accent-fg`. */
const HEADER_PARTS_TINT_ON_TINT = headerParts(
  (name) => whole(`${name}-fg`),
  whole('accent-fg'),
  tint('accent', 0.15),
);

/** Everything the header's controls fall short on in `theme`. */
function headerShortfalls(theme: Theme, parts: HeaderPart[]): string[] {
  const { tokens } = theme;
  const over = (under: RGB, { token, share }: LinkPart): RGB =>
    toRgb(composite(tokens[token], under, share));
  const out: string[] = [];
  for (const { what, fg, on, least } of parts) {
    const backdrop = on.reduce(over, tokens[LINK_BAR]);
    const value = contrast(over(backdrop, fg), backdrop);
    if (value < least) out.push(`${theme.id}: ${what} is ${value.toFixed(1)}, under ${least}`);
  }
  return out;
}

describe("the header's controls read on every theme", () => {
  it('measures every tone-coloured part of the header in its readable colour', () => {
    expect(HEADER_PARTS).toHaveLength(12);
    const colours = new Set(HEADER_PARTS.map(({ fg }) => fg.token));
    expect([...colours].sort()).toEqual(['accent-fg', 'text-primary', 'warning-fg']);
  });

  it('every label, icon and focus ring holds in EVERY theme', () => {
    expect(themes.flatMap((theme) => headerShortfalls(theme, HEADER_PARTS))).toEqual([]);
  });

  it('fails on what it drew before: the bare accent and warning, and a ring at 70%', () => {
    const before = themes.flatMap((theme) => headerShortfalls(theme, HEADER_PARTS_BEFORE));
    expect(before).toEqual(
      expect.arrayContaining([
        "ayu-light: the active tab's label is 1.9, under 4.5",
        'ayu-light: the focus ring against the bar is 1.7, under 3',
        "ayu-light: the locked status chip's label is 1.7, under 4.5",
      ]),
    );
    const count = (what: string) => before.filter((line) => line.includes(`: ${what} is`)).length;
    expect(count("the active tab's label")).toBe(34);
    expect(count('the focus ring against the bar')).toBe(23);
  });

  it('fails on a tint over a tint: the readable accent is solved for one tint, not two', () => {
    const stacked = themes.flatMap((theme) => headerShortfalls(theme, HEADER_PARTS_TINT_ON_TINT));
    expect(stacked.length).toBeGreaterThan(0);
    expect(stacked.every((line) => line.includes('the unpushed count on the Workspace page'))).toBe(
      true,
    );
  });
});

/**
 * What a focus ring is drawn against: the panel and dialog fills a control sits
 * on (`card`, `surface`), and the row tints of a diff, which the unpushed-changes
 * list's inset ring is drawn over (`diff-add`, `diff-del`). Every
 * `focus-visible:ring-*` in ui-components is `ring-accent-fg`: the header's,
 * the `Tabs` primitive's, `SectionLanding`'s cards' and that list's.
 */
const RING_BACKDROPS = ['card', 'surface', 'diff-add', 'diff-del'] as const;

/** Every backdrop `ring` falls under 3:1 against in `theme`. */
function ringShortfalls(theme: Theme, ring: LinkPart): string[] {
  const { tokens } = theme;
  return RING_BACKDROPS.flatMap((backdrop) => {
    const under = tokens[backdrop];
    const value = contrast(toRgb(composite(tokens[ring.token], under, ring.share)), under);
    return value < NON_TEXT_MIN_CONTRAST
      ? [`${theme.id}: the focus ring on ${backdrop} is ${value.toFixed(1)}, under 3`]
      : [];
  });
}

describe('every focus ring shows on every theme', () => {
  it('the readable accent holds 3:1 against every backdrop a ring is drawn on, in EVERY theme', () => {
    expect(themes.flatMap((theme) => ringShortfalls(theme, whole('accent-fg')))).toEqual([]);
  });

  it('fails on the ring it replaced, 70% of the accent, on every backdrop', () => {
    const before = themes.flatMap((theme) => ringShortfalls(theme, tint('accent', 0.7)));
    const on = (backdrop: string) => before.filter((line) => line.includes(` on ${backdrop} is`));
    expect(on('card')).toHaveLength(23);
    expect(on('surface')).toHaveLength(22);
    expect(on('diff-add')).toHaveLength(39);
    expect(on('diff-del')).toHaveLength(36);
    expect(before).toContainEqual(
      expect.stringMatching(/^ayu-light: the focus ring on diff-del is 1\.\d, under 3$/),
    );
  });
});

/**
 * A field's, a checkbox's and a radio's focus and checked state: a colour, the
 * fills it is drawn against (`on`), and a tint between them where there is one
 * (`over`). A field and the ring around a box sit on the panel (`card` or
 * `surface`); a box's own face is `card`, and a ticked one `accent/20` over it.
 * A native checkbox or radio is filled with its `accent-color` when ticked, on
 * the panel. ui-components' Input, Checkbox and Radio tests hold the classes to
 * these, and its controlColours test every focus and ticked colour in the source.
 */
interface FieldPart {
  what: string;
  fg: LinkPart;
  on: readonly string[];
  over?: LinkPart;
}
const PANEL = ['card', 'surface'] as const;

function fieldParts(
  accent: LinkPart,
  danger: LinkPart,
  boxRing: LinkPart,
  checked: LinkPart,
  nativeTick: LinkPart,
  caution: LinkPart,
): FieldPart[] {
  return [
    { what: "a field's focus edge and ring", fg: accent, on: PANEL },
    { what: "an invalid field's focus edge and ring", fg: danger, on: PANEL },
    { what: "a checkbox's or radio's focus ring", fg: boxRing, on: PANEL },
    { what: "a ticked box's edge, and a chosen radio's dot", fg: checked, on: ['card'] },
    { what: 'the tick', fg: checked, on: ['card'], over: tint('accent', 0.2) },
    { what: "a native checkbox's or radio's ticked fill", fg: nativeTick, on: PANEL },
    { what: "the export's credential checkbox, ticked", fg: caution, on: PANEL },
  ];
}
const FIELD_PARTS = fieldParts(
  whole('accent-fg'),
  whole('danger-fg'),
  whole('accent-fg'),
  whole('accent-fg'),
  whole('accent-fg'),
  whole('warning-fg'),
);
/**
 * What they drew before: a 30% / 40% ring beside the bare tone's edge, a 50% box
 * ring, the bare accent, and amber for the credential checkbox.
 */
const FIELD_PARTS_BEFORE = fieldParts(
  tint('accent', 0.3),
  tint('danger', 0.4),
  tint('accent', 0.5),
  whole('accent'),
  whole('accent'),
  whole('amber'),
);

/** The default theme's tokens (`:root`): what a theme that leaves one out inherits. */
const ROOT_TOKENS = themes.find(({ id }) => id === 'studio-dark')?.tokens ?? {};

/** Everything the fields and boxes fall short on in `theme`, under 3:1 (WCAG 1.4.11). */
function fieldShortfalls(theme: Theme, parts: FieldPart[]): string[] {
  const { tokens } = theme;
  const paint = ({ token, share }: LinkPart, under: RGB): RGB =>
    toRgb(composite(tokens[token] ?? ROOT_TOKENS[token], under, share));
  return parts.flatMap(({ what, fg, on, over }) =>
    on.flatMap((fill) => {
      const under = over ? paint(over, tokens[fill]) : tokens[fill];
      const value = contrast(paint(fg, under), under);
      return value < NON_TEXT_MIN_CONTRAST
        ? [`${theme.id}: ${what} on ${fill} is ${value.toFixed(1)}, under 3`]
        : [];
    }),
  );
}

describe("the app's default focus ring shows on every theme", () => {
  // `*:focus-visible` in global.css is the ring of every native checkbox and
  // radio and of any control that draws none of its own.
  const rule = css.match(/\*:focus-visible\s*\{([^}]*)\}/)?.[1] ?? '';

  it('is a solid outline in the accent readable colour', () => {
    expect(rule).toMatch(/outline:\s*2px solid rgb\(var\(--accent-fg\)\);/);
    expect(rule).not.toMatch(/--accent\)/);
  });

  it('holds 3:1 against the panel in EVERY theme, where the bare accent did not', () => {
    const under = (ring: LinkPart) =>
      themes.flatMap((theme) =>
        ringShortfalls(theme, ring).filter((line) => / on (card|surface) is/.test(line)),
      );
    expect(under(whole('accent-fg'))).toEqual([]);
    expect(under(whole('accent'))).toEqual([
      expect.stringMatching(/^ayu-light: the focus ring on card is 2\.\d, under 3$/),
      expect.stringMatching(/^ayu-light: the focus ring on surface is 2\.\d, under 3$/),
      expect.stringMatching(/^tokyo-night-day: the focus ring on card is 2\.\d, under 3$/),
    ]);
  });
});

describe('fields, checkboxes and radios show focus and state on every theme', () => {
  it('every focus edge, ring, tick and dot holds 3:1 in EVERY theme', () => {
    expect(themes.flatMap((theme) => fieldShortfalls(theme, FIELD_PARTS))).toEqual([]);
  });

  it('fails on what they drew before: faint rings everywhere, and the bare accent tick', () => {
    const before = themes.flatMap((theme) => fieldShortfalls(theme, FIELD_PARTS_BEFORE));
    const count = (what: string, fill: string) =>
      before.filter((line) => line.includes(`: ${what} on ${fill} is`)).length;
    expect(count("a field's focus edge and ring", 'card')).toBe(60);
    expect(count("an invalid field's focus edge and ring", 'card')).toBe(60);
    expect(count("a checkbox's or radio's focus ring", 'card')).toBe(51);
    expect(count('the tick', 'card')).toBe(10);
    expect(before).toContainEqual(
      expect.stringMatching(/^ayu-light: the tick on card is 1\.\d, under 3$/),
    );
    // A native box ticked in the bare accent, and the credential box in amber.
    expect(count("a native checkbox's or radio's ticked fill", 'card')).toBe(2);
    expect(count("a native checkbox's or radio's ticked fill", 'surface')).toBe(1);
    expect(count("the export's credential checkbox, ticked", 'card')).toBe(9);
    expect(count("the export's credential checkbox, ticked", 'surface')).toBe(6);
  });
});

describe('solveDiffTint', () => {
  // A mid grey over white: 20% of it is 7.5 from the page, and 27% the first share 10 from it.
  const white: RGB = [255, 255, 255];
  const black: RGB = [0, 0, 0];
  const grey: RGB = [128, 128, 128];
  const at = (tone: RGB, page: RGB, share: number): RGB =>
    toRgb(composite(tone, page, share / 100).map(Math.round));
  const readable = (code: RGB, number: RGB, tint: RGB): boolean =>
    contrast(code, tint) >= DIFF_CODE_MIN_CONTRAST &&
    contrast(number, tint) >= DIFF_NUMBER_MIN_CONTRAST;

  it('is the floor where the floor already stands off the page', () => {
    const green: RGB = [0, 255, 0];
    expect(solveDiffTint(green, black, white, white)).toEqual(at(green, black, DIFF_TINT_FLOOR));
  });

  it('takes the least more that reaches the target where the floor is too faint', () => {
    const tint = solveDiffTint(grey, white, black, black);
    expect(tint).toEqual(at(grey, white, 27));
    expect(difference(tint, white)).toBeGreaterThanOrEqual(DIFF_TINT_TARGET);
    expect(difference(at(grey, white, 26), white)).toBeLessThan(DIFF_TINT_TARGET);
  });

  it('stops short of the target when one more share would take the code under AA', () => {
    const code: RGB = [101, 101, 101];
    const tint = toRgb(solveDiffTint(grey, white, code, black));
    expect(tint).toEqual(at(grey, white, 22));
    expect(difference(tint, white)).toBeLessThan(DIFF_TINT_TARGET);
    expect(readable(code, black, tint)).toBe(true);
    expect(readable(code, black, at(grey, white, 23))).toBe(false);
  });

  it('stops short of the target when one more share would take the line number under 3:1', () => {
    const number: RGB = [130, 130, 130];
    const tint = toRgb(solveDiffTint(grey, white, black, number));
    expect(tint).toEqual(at(grey, white, 21));
    expect(readable(black, number, tint)).toBe(true);
    expect(readable(black, number, at(grey, white, 22))).toBe(false);
  });

  it('goes under the floor when the text cannot take the floor', () => {
    const code: RGB = [110, 110, 110];
    expect(readable(code, black, at(grey, white, DIFF_TINT_FLOOR))).toBe(false);
    // The most the code can take, and it is still a tint: 11% of the grey.
    expect(solveDiffTint(grey, white, code, black)).toEqual(at(grey, white, 11));
    expect(readable(code, black, at(grey, white, 11))).toBe(true);
    expect(readable(code, black, at(grey, white, 12))).toBe(false);
  });

  it('is the bare page when the text does not read even there', () => {
    const faint: RGB = [150, 150, 150];
    expect(solveDiffTint(grey, white, faint, faint)).toEqual(white);
  });

  it('ends at the tone itself when the tone is the page: no share can stand off it', () => {
    expect(solveDiffTint(white, white, black, black)).toEqual(white);
  });

  it('never goes under the floor to meet the target sooner: near black the measure is not to be trusted', () => {
    const green: RGB = [100, 250, 120];
    // 2% of the tone over black is `2 5 2`: 10 by the measure, and not a colour a display shows.
    expect(difference(at(green, black, 2), black)).toBeGreaterThanOrEqual(DIFF_TINT_TARGET);
    expect(solveDiffTint(green, black, white, white)).toEqual(at(green, black, DIFF_TINT_FLOOR));
  });
});

describe('difference', () => {
  it('knows black from white, and a colour from itself', () => {
    expect(difference([10, 20, 30], [10, 20, 30])).toBe(0);
    expect(difference([0, 0, 0], [255, 255, 255])).toBeCloseTo(100, 0);
  });

  it('tells a red from a green of the same lightness, where a contrast ratio cannot', () => {
    const red: RGB = [200, 60, 60];
    const green: RGB = [40, 127, 40];
    expect(contrast(red, green)).toBeLessThan(1.1);
    expect(difference(red, green)).toBeGreaterThan(20);
  });
});

describe('generate', () => {
  const block = (lines: string[]): string => `[data-theme='t'] {\n${lines.join('\n')}\n}\n`;
  const tones = [
    '  --surface: 255 255 255;',
    '  --card: 250 250 250;',
    '  --text-primary: 0 0 0;',
    '  --text-muted: 60 60 60;',
    '  --accent: 0 90 200;',
    '  --success: 128 128 128;',
    '  --warning: 150 100 0;',
    '  --danger: 60 0 0;',
    '  --info: 0 110 140;',
  ];

  it('writes a theme its foregrounds, its diff tints and its solid accent, after the tones they come from', () => {
    const out = generate(block([...tones, '  --purple: 1 2 3;']));
    const names = [...out.matchAll(/--([\w-]+):/g)].map((match) => match[1]);
    expect(names.slice(names.indexOf('info'))).toEqual([
      'info',
      ...FG_TONES.map((tone) => `${tone}-fg`),
      'diff-add',
      'diff-del',
      'on-accent',
      'accent-hover',
      'purple',
    ]);
    // The grey is raised to the target (27%); the dark red stands off white at the floor (20%).
    expect(out).toContain('--diff-add: 221 221 221;');
    expect(out).toContain('--diff-del: 216 204 204;');
    // White reads on the blue at AA, so the label is the page itself.
    expect(out).toContain('--on-accent: 255 255 255;');
    expect(generate(out)).toBe(out);
  });

  it('replaces a stale generated token instead of keeping it or writing a second', () => {
    const stale = block([
      ...tones,
      '  --diff-add: 9 8 7;',
      '  --diff-del: 7 8 9;',
      '  --on-accent: 9 8 7;',
      '  --accent-hover: 7 8 9;',
    ]);
    const out = generate(stale);
    expect(out).toBe(generate(block(tones)));
    expect(out.match(/--diff-add:/g)).toHaveLength(1);
    expect(out.match(/--on-accent:/g)).toHaveLength(1);
    expect(out.match(/--accent-hover:/g)).toHaveLength(1);
    expect(out).not.toContain('9 8 7');
  });

  it('refuses a theme without the line-number colour the diff tints are solved against', () => {
    const missing = tones.filter((line) => !line.includes('--text-muted'));
    expect(() => generate(block(missing))).toThrow("Theme 't' does not define --text-muted");
  });
});
