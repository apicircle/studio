/**
 * Adapter between `VsCodeBridge.activeWorkspace()` and the MCP host's
 * `WorkspaceProvider` interface. Reads from / writes to the same surface
 * the editor commands use, so MCP tool calls see the exact in-memory state
 * the user just edited (no disk-snapshot lag).
 *
 * NOTE: if the user switches workspaces while a client is connected, the
 * provider follows the active workspace — by design. The MCP catalog
 * already supports multi-workspace addressing via `workspace.list` /
 * `workspace.setActive`; the embedded host inherits that.
 */
class BridgeWorkspaceProvider implements WorkspaceProvider {
  constructor(private readonly bridge: VsCodeBridge) {}

  private surface(): WorkspaceSurface {
    const active = this.bridge.activeWorkspace();
    if (!active) {
      throw new Error(
        'BridgeWorkspaceProvider: no active workspace. Open a folder containing .apicircle/workspace.json before invoking MCP tools.',
      );
    }
    return active;
  }

  read(): Promise<WorkspaceState> {
    return this.surface().read();
  }

  async apply(patch: WorkspacePatch): Promise<{ state: WorkspaceState; changedIds: string[] }> {
    const surface = this.surface();
    const result = await surface.apply(patch);
    const state = await surface.read();
    return {
      state,
      changedIds: result.changedIds ?? [],
    };
  }

  write(next: { synced?: WorkspaceSynced; local?: WorkspaceLocal }): Promise<WorkspaceState> {
    return this.surface().write(next);
  }
}
